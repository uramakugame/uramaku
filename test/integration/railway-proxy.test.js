'use strict';
const assert=require('node:assert/strict');
const {settings,address,AbuseGuard}=require('../../server/abuse-guard');
const socket=(id,real,forwarded='192.0.2.77, 198.51.100.99')=>({id,data:{},handshake:{address:'::ffff:100.64.0.2',headers:{'x-real-ip':real,'x-forwarded-for':forwarded}}});
assert.equal(settings({}).trustRailwayProxy,false);
for(const value of ['true','-1','2','1.1'])assert.throws(()=>settings({TRUST_RAILWAY_PROXY:value}));
assert.throws(()=>settings({TRUST_RAILWAY_PROXY:'1'}),/Railway deployment/);
assert.throws(()=>settings({TRUST_RAILWAY_PROXY:'1',RAILWAY_PROJECT_ID:'test',TRUSTED_PROXY_HOPS:'1'}),/not both/);
assert(settings({TRUST_RAILWAY_PROXY:'1',RAILWAY_ENVIRONMENT_ID:'test'}).trustRailwayProxy);
const a=socket('a','203.0.113.1'),b=socket('b','203.0.113.2'),same=socket('same','203.0.113.1','192.0.2.1');
assert.equal(address(a),'100.64.0.2','Untrusted X-Real-IP is ignored locally');
assert.equal(address(a,1),'198.51.100.99','Generic fixed-hop behavior remains available');
assert.equal(address(a,0,true),'203.0.113.1');assert.equal(address(b,0,true),'203.0.113.2');
assert.equal(address(same,0,true),'203.0.113.1','Changing X-Forwarded-For cannot change Railway-mode identity');
assert.equal(address(socket('v6','2001:db8::7'),0,true),'2001:db8::7');
assert.equal(address(socket('mapped','::ffff:203.0.113.1'),0,true),'203.0.113.1');
for(const raw of [undefined,null,[],['203.0.113.1'],'','bad','203.0.113.1, 203.0.113.2','https://203.0.113.1','fe80::1%lo0','a'.repeat(65)])assert.equal(address(socket('invalid',raw),0,true),'100.64.0.2');
const config=settings({TRUST_RAILWAY_PROXY:'1',RAILWAY_PROJECT_ID:'test',MAX_CONNECTIONS_PER_IP:'1',RATE_CREATE_PER_10_MIN:'1'});
const guard=new AbuseGuard(config,()=>0);assert(guard.admit(a));assert(guard.admit(b));assert(!guard.admit(same));
assert(guard.allow(a,'createRoom',{}));assert(!guard.allow(same,'createRoom',{}));assert(guard.allow(b,'createRoom',{}));
guard.release(a);assert(guard.admit(same));assert.equal(guard.total,2);
assert.equal(guard.connections.get('203.0.113.1'),1);assert.equal(guard.connections.get('203.0.113.2'),1);
console.log('Explicit Railway IP trust, startup guards, IPv4/IPv6, invalid-header fallback, independent/shared quotas, release and unchanged local/fixed-hop behavior passed.');
