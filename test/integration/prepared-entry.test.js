'use strict';
const assert=require('node:assert/strict');
const harness=require('../helpers/server-harness');
const h=harness(),host=h.client('h');
const prepared=host.send('prepareEntry',{kind:'create',nickname:'Host'});
assert(prepared.intentId&&prepared.resumeToken);assert.equal(h.rooms.size,0,'Preparing a token must not occupy a seat');
assert(!JSON.stringify(h.store.db.prepare('SELECT * FROM entry_intents').all()).includes(prepared.resumeToken));
assert(host.send('confirmEntry',{code:prepared.code,intentId:prepared.intentId,token:'0'.repeat(64)}).error);assert.equal(h.rooms.size,0);
assert(host.send('confirmEntry',{code:prepared.code,intentId:prepared.intentId,token:prepared.resumeToken}).ok);
const room=h.rooms.get(prepared.code);assert.equal(room.players.length,1);
assert.notEqual(room.players[0].id,'h','Prepared seats have a transport-independent identity');
assert.equal(h.store.entry(prepared.intentId),undefined,'Membership and intent consumption commit together');
assert(host.send('confirmEntry',{code:prepared.code,intentId:prepared.intentId,token:prepared.resumeToken}).ok,'A lost confirmation ACK can be retried');
assert.equal(room.players.length,1);
const next=h.client('next');const joining=next.send('prepareEntry',{kind:'join',code:room.code,nickname:'Guest'});
assert.equal(room.players.length,1);
// Refresh between preparation and confirmation finalizes the saved intent.
const refreshed=h.client('refresh');
assert(refreshed.send('resumeSession',{code:room.code,token:joining.resumeToken,intentId:joining.intentId}).ok);
assert.equal(room.players.length,2);assert.equal(next.data.playerId,undefined);
assert(!JSON.stringify(host.events).includes(joining.resumeToken),'Other players never receive the credential');
const rev=room.revision,guest=room.players[1];
assert(refreshed.send('leaveRoom').ok);assert.equal(room.revision,rev+1);
assert(h.client('bad-resume').send('resumeSession',{code:room.code,token:joining.resumeToken}).error);
assert.equal(room.seatTokens.has(guest.id),false);
const expiring=h.client('expiring').send('prepareEntry',{kind:'join',code:room.code,nickname:'Later'});
h.store.db.prepare('UPDATE entry_intents SET expires_at=0 WHERE id=?').run(expiring.intentId);
assert(h.client('late').send('confirmEntry',{code:room.code,token:expiring.resumeToken,intentId:expiring.intentId}).error);
assert.equal(room.players.length,1);
// No state/ACK that claims success may be emitted before a successful commit.
const original=JSON.stringify(room),count=host.events.length;
h.store.beforeCommit=()=>{throw Error('disk unavailable');};
assert.equal(host.send('setTreasuryMode',{enabled:true}).error,'The request could not be completed.');
assert.equal(JSON.stringify(room),original);assert(!host.events.slice(count).some(e=>e.event==='state'));
h.store.beforeCommit=null;
const recoveredConfirm=h.client('confirm-after-reconnect');
assert(recoveredConfirm.send('confirmEntry',{code:prepared.code,intentId:prepared.intentId,token:prepared.resumeToken}).ok);
assert.equal(host.closed,true);assert.equal(room.players.length,1,'A repeated confirmation on a fresh connection resumes the existing seat');
console.log('Prepared credentials, atomic membership, lost confirmation ACKs, recovery before confirm, expiry, revocation and commit-before-broadcast passed.');
