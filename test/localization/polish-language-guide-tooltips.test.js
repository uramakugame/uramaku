'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const i18n=require('../../shared/i18n');
const roles=require('../../shared/roles');
const app=fs.readFileSync(path.join(__dirname,'../../public/js/app.js'),'utf8');
const tutorial=fs.readFileSync(path.join(__dirname,'../../public/js/tutorial.js'),'utf8');
const styles=fs.readFileSync(path.join(__dirname,'../../public/css/game.css'),'utf8');
const en=i18n.get('treasuryModeHtml','en');
const jp=i18n.get('treasuryModeHtml','jp');
for(const html of [en,jp]){
 assert(html.includes('class="howto-steps treasury-steps"'),'Treasury rules must be numbered');
 assert(html.includes('class="basic-rules treasury-basic-actions"'),'Riot actions must use guide action rows');
 assert.equal((html.match(/<li>/g)||[]).length,5,'Treasury has five numbered steps in its own tab');
 assert(!html.includes('class="treasury-riot-actions"'),'Old Riot presentation should be removed');
}
assert(en.includes('Basic actions (Riot)'));
assert(jp.includes('基本アクション（暴動中）'));
// A selection of every distinct concise announcement generated by announcementForLog.
const announcements=[
 'Akira loots 1 coin from Mei',
 'Riot breaks out! Earn becomes Loot; Purge becomes Overthrow.',
 'Riot ends. Normal actions return.',
 'Akira wins by wealth with 14 coins!',
 'Mei earns 1 coin',
 'Akira uses Purge against Mei',
 'Mei uses Overthrow against Akira',
 'Akira claims Lord (Tax) and targets Mei.',
 'Mei claims Swordsman (Hire Guard)',
 "Akira's challenge succeeds! Mei must lose an Influence",
 "Mei's challenge fails",
 'Akira and Mei exchange influences privately',
 'Akira pays 1 coin to Mei to conceal their influences',
 "Mei's Intimidate succeeds.",
 'Akira resolves Hire Guard against Mei',
 'Akira gains 2 coins from Tax',
 'Mei pays 1 coin to the treasury',
 'Mei takes 2 coins from Akira',
 'Mei investigates Akira',
 'Mei pays 2 coins to conceal information',
 'Akira reveals all unknown influences',
 'Akira cannot conceal their influences',
 'Mei reveals Intrigue results about Akira',
 'Mei keeps Intrigue results private',
 'Mei loses Swordsman',
 'Mei loses an influence',
 'Akira is eliminated',
 'Akira wins the game!'
];
const leftover=/\b(?:loots?|claims?|challeng(?:e|es|ing)|exchange|influences?|pays?|conceal|resolve|succeeds?|fails?|gains?|takes?|investigates?|reveals?|unknown|private|loses?|eliminated|wealth|wins?|Treasury|Riot)\b/i;
for(const message of announcements){
 const translated=i18n.translate(message,'jp');
 assert(/[ぁ-んァ-ン一-龯]/.test(translated),`Announcement remains English: ${message}`);
 assert(!leftover.test(translated),`Announcement partially untranslated: ${message} => ${translated}`);
 assert.equal(i18n.translate(message,'en'),message,'English announcements remain unchanged');
}
const functionSource=app.match(/function roleHint\(role\)\{[\s\S]*?^\}/m)?.[0];
assert(functionSource,'Role tooltip function is available');
for(const lang of ['en','jp'])for(const revealFactions of [false,true]){
 const roleHint=vm.runInNewContext(`${functionSource};roleHint('lord')`,{
  state:{roles,revealFactions},referenceLanguage:lang,t:key=>i18n.get(key,lang)
 });
 assert.equal(roleHint.includes(' · '),revealFactions,'Tooltip faction should follow Show hidden factions setting');
 assert(roleHint.includes(i18n.role('lord',lang)));
}
const tip=require('../../public/js/components/role-tooltips');
assert(!tip.content({raw:'Lord · Order\nAction — Tax: Collect 2 coins.',revealFactions:false}).includes('tooltip-faction'),'Standard tooltip omits faction');
assert(tip.content({raw:'Lord · Order\nAction — Tax: Collect 2 coins.',revealFactions:true}).includes('tooltip-faction'),'Faction mode tooltip includes faction');
assert(!tutorial.includes('<div class="tooltip-faction">'),'Tutorial Standard Mode should not show faction text in tooltip');
assert(styles.includes('calc(clamp(10px,5.5cqw,15px) + 2pt)'));
assert(styles.includes('calc(clamp(11px,6.4cqw,18px) + 2pt)'));
assert(styles.includes('calc(clamp(11px,0.88vw,14px) + 2pt)'));
console.log('Concealed-faction tooltips, translated announcements, numbered Treasury rules, Riot basic actions and +2pt labels passed.');
