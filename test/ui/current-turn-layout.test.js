const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const dir=path.join(__dirname,'../../public');
const app=fs.readFileSync(path.join(dir,'js/app.js'),'utf8');
const tutorial=fs.readFileSync(path.join(dir,'js/tutorial.js'),'utf8');
const currentTurnCss=fs.readFileSync(path.join(dir,'css/source/04-component-overrides.css'),'utf8');
const noticeCss=fs.readFileSync(path.join(dir,'css/source/05-announcements.css'),'utf8');
assert(app.includes('class="flow-status"'),'Current Turn text needs its own layout column');
assert(app.includes("flow.classList.add('has-decision')"),'All decision kinds should be laid out beside the current turn status');
assert(currentTurnCss.includes('.action-flow.has-decision{'),'Decision panel must use the side-by-side layout');
assert(currentTurnCss.includes('grid-template-columns:minmax(215px,1fr) minmax(0,1.25fr)'),'Decision panel should reserve columns for status and controls');
assert(currentTurnCss.includes('@media(max-width:1040px)'),'Narrow screens need the wrapping fallback');
assert(app.includes("(visibility&1)?'Privately revealed':'Hidden'"),'Own unrevealed roles should show Hidden');
assert(!require('../../public/js/components/role-cards').hidden().includes('<small>'),"Other players' standard hidden backs must have no visible status text");
assert(!app.includes('<small>Hidden</small>'),"Opponents' hidden card backs must not show Hidden text");
assert(require('../tutorial/browser-harness').harness().app.querySelector('[data-player-id="you"]').textContent.includes('Hidden'));
assert(!tutorial.includes('<small>Hidden</small>'),"Tutorial opponents' hidden backs must not show Hidden text");
assert(require('../../public/js/components/role-cards').hidden().includes('aria-label="Hidden role"'),'Hidden card accessibility labels should remain');
assert(tutorial.includes('URAMAKU_ROLE_CARDS.hidden({slot})'),'Tutorial hidden card should use the shared hidden-card element');
assert(noticeCss.includes('overflow:visible'),'Announcements must not be clipped by their stack');
assert(noticeCss.includes('max-height:none'),'Stack must not truncate its last notification');
assert(noticeCss.includes('flex:0 0 auto'),'Announcements must not shrink when more arrive');
console.log('Current Turn, responsive decision layout, restored hidden labels, and notification clipping checks passed.');
