const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const app = fs.readFileSync(path.join(__dirname,'../../public/js/app.js'),'utf8');
const layout = fs.readFileSync(path.join(__dirname,'../../public/css/source/08-responsive-room.css'),'utf8');
const old = fs.readFileSync(path.join(__dirname,'../../public/css/source/04-component-overrides.css'),'utf8');
assert(layout.includes('grid-template-columns:repeat(4,minmax(0,1fr))!important'));
assert(layout.includes('grid-template-rows:repeat(2,minmax('), 'Board must reserve two player rows even in small games');
assert(layout.includes('grid-template-rows:repeat(8,minmax(32px,1fr))!important'),'Actions should scale to board height');
assert(layout.includes('.game-sidebar>.game-deck-panel{\n    grid-column:3;grid-row:1'),'Deck must occupy the Current Turn row');
assert(layout.includes('grid-column:3;grid-row:2;align-self:stretch'),'Game Log must align to the player board row');
assert(layout.includes('min-width:0!important'),'Board must be allowed to shrink without 700px scroll floor');
assert(!old.includes('min-height:clamp(480px'),'Board height must not be pinned to old desktop floor');
const start=app.indexOf('if(targetSelectionAction){');
const end=app.indexOf("document.getElementById('dismissMandatoryPurge')",start);
assert(start>0 && end>start);
const targetFlow=app.slice(start,end);
assert(targetFlow.includes("document.querySelector('.game-layout .action-flow')"),'Target prompt must live beside Current Turn');
assert(targetFlow.includes("flow.classList.add('has-decision','has-target-selection','flow-attention')"),'Target uses the shared side decision layout');
assert(targetFlow.includes('aria-label="Select action target"'),'Target decision should be accessible');
assert(!targetFlow.includes("panel?.insertAdjacentHTML('afterbegin'"),'Do not add a target-selection banner to the player board');
assert(targetFlow.includes("const compulsory=state.mandatoryPurge&&targetSelectionAction==='purge'"),'Mandatory Purge remains automatic');
assert(targetFlow.includes("card.classList.add('selectable-target')"),'Player cards must remain selectable');
assert(targetFlow.includes("send('action',{action,targetId:candidate.id})"));
assert(layout.includes('@media (max-width:959px)'),'Very narrow widths should stack rather than destroy card readability');
console.log('Responsive two-row board, synchronized Actions and Game Log, Current Turn target prompt passed.');
